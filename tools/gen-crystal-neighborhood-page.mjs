/**
 * Build docs/crystal-neighborhoods.html - the mineral-neighborhood plate.
 *
 * Reads data/generated/crystal-flow-tree.json (tools/gen-crystal-flow-tree.mjs)
 * and injects it into tools/crystal-neighborhood-page.template.html.
 *
 * UNLIKE the flow plate, this page KEEPS every citation. The flow plate draws
 * chords and trims `cites` because it shows no receipts; here the receipt IS
 * the feature - a line the reader cannot audit should not be drawn.
 *
 *   node tools/gen-crystal-neighborhood-page.mjs [--out docs/crystal-neighborhoods.html]
 */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const DATA = path.join(ROOT, 'data', 'generated', 'crystal-flow-tree.json');
const TEMPLATE = path.join(ROOT, 'tools', 'crystal-neighborhood-page.template.html');
const MARKER = '/*__FLOW_DATA__*/null';

function flag(name, fallback) {
  const i = process.argv.indexOf(name);
  return i >= 0 && process.argv[i + 1] ? process.argv[i + 1] : fallback;
}
const OUT = path.resolve(ROOT, flag('--out', 'docs/crystal-neighborhoods.html'));

function gitDescribe() {
  try {
    return execFileSync('git', ['rev-parse', '--short', 'HEAD'], { cwd: ROOT, encoding: 'utf8' }).trim();
  } catch { return 'unknown'; }
}

function simVersion() {
  const source = fs.readFileSync(path.join(ROOT, 'js', '15-version.ts'), 'utf8');
  const match = source.match(/const\s+SIM_VERSION\s*=\s*(\d+)/);
  return match ? match[1] : '?';
}

/**
 * Emit the payload as pure ASCII - mineral descriptions carry degree and
 * multiplication signs, and not every host that serves this file declares a
 * charset.
 */
function asciiOnly(text) {
  let out = '';
  for (const ch of text) {
    if (ch.codePointAt(0) <= 126) { out += ch; continue; }
    for (let i = 0; i < ch.length; i++) {
      out += '\\u' + ch.charCodeAt(i).toString(16).padStart(4, '0');
    }
  }
  return out;
}

if (!fs.existsSync(DATA)) {
  console.error('[neighborhood-page] FAIL: run tools/gen-crystal-flow-tree.mjs first');
  process.exit(1);
}

const flow = JSON.parse(fs.readFileSync(DATA, 'utf8'));

/* The page draws one arrow per (from, to, relation) and lists every receipt
 * behind it, so a missing cite is a page that cannot keep its promise. */
const uncited = flow.edges.filter(e => !e.evidence || !(e.evidence.cites || []).length);
if (uncited.length) {
  console.error('[neighborhood-page] FAIL: ' + uncited.length + ' edge(s) carry no citation, '
    + 'and this page promises a receipt for every line. First: '
    + uncited[0].from + ' -> ' + uncited[0].to);
  process.exit(1);
}

const sim = simVersion();
const commit = gitDescribe();
flow._stamp = 'Vugg Simulator - SIM ' + sim + ' - ' + commit;
flow._provenance = 'Generated by tools/gen-crystal-neighborhood-page.mjs from data/minerals.json, '
  + 'the nucleation engines js/80-js/91 and the runtime census in '
  + 'data/generated/substrate-escape-census.json at SIM ' + sim + ' (' + commit + '). '
  + 'Regenerate with: node tools/substrate-escape-census.mjs && '
  + 'node tools/gen-crystal-flow-tree.mjs && node tools/gen-crystal-neighborhood-page.mjs';

const template = fs.readFileSync(TEMPLATE, 'utf8');
if (!template.includes(MARKER)) {
  console.error('[neighborhood-page] FAIL: the FLOW_DATA marker is missing from the template');
  process.exit(1);
}

const payload = asciiOnly(JSON.stringify(flow).replace(/<\//g, '<\\/'));
const html = template.replace(MARKER, () => payload);

const stray = [...html].filter(ch => ch.codePointAt(0) > 126);
if (stray.length) {
  console.error('[neighborhood-page] FAIL: ' + stray.length
    + ' non-ASCII character(s) survived into the page');
  process.exit(1);
}

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, html, 'ascii');

const receipts = flow.edges.reduce((n, e) => n + (e.evidence.runtime || []).length, 0);
console.error('[neighborhood-page] wrote ' + path.relative(ROOT, OUT) + ' ('
  + Math.round(html.length / 1024) + ' KB, ' + flow.counts.minerals + ' species, '
  + flow.counts.edges + ' edges, ' + receipts + ' runtime receipts, SIM ' + sim + ')');
